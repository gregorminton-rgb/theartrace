import subprocess
import json
import os
from PIL import Image

# 1. Get the list of 52 images from git diff between 74836bc and 02f85d9
out = subprocess.check_output(['git', 'diff', '--name-only', '74836bc', '02f85d9'], text=True)
files = [f.strip() for f in out.splitlines() if f.strip().startswith('images/art/')]

print(f"Restoring {len(files)} clean, full-bleed artworks from commit 74836bc...")

for file_path in files:
    # Read binary from commit 74836bc
    cmd = ['git', 'show', f'74836bc:{file_path}']
    data = subprocess.check_output(cmd)
    with open(file_path, 'wb') as f:
        f.write(data)
    
    # Verify image opens with PIL
    try:
        im = Image.open(file_path)
        print(f"  Restored {file_path}: {im.size}")
    except Exception as e:
        print(f"  Error verifying {file_path}: {e}")

# 2. Update artwork-images.js metadata for these 52 files
raw_748 = subprocess.check_output(['git', 'show', '74836bc:artwork-images.js'], text=True)
prefix = 'window.ART_ARTWORK_IMAGES = '

# Extract JSON from 74836bc
json_str_748 = raw_748[raw_748.index(prefix) + len(prefix):].rstrip(';\n\r ')
data_748 = json.loads(json_str_748)

with open('artwork-images.js', 'r', encoding='utf-8') as f:
    cur_text = f.read()

json_str_cur = cur_text[cur_text.index(prefix) + len(prefix):].rstrip(';\n\r ')
data_cur = json.loads(json_str_cur)

# Overwrite entries in data_cur for the 52 restored files
restored_count = 0
for work_id, entry in data_748['images'].items():
    if entry.get('file') in files:
        data_cur['images'][work_id] = entry
        restored_count += 1

print(f"Updated {restored_count} entries in artwork-images.js")

with open('artwork-images.js', 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/import-artwork-images.ps1 - do not edit by hand. */\n')
    f.write('window.ART_ARTWORK_IMAGES = ')
    json.dump(data_cur, f, indent=4)
    f.write(';\n')

print("Successfully restored 52 clean, full-bleed paintings and updated artwork-images.js.")
